"""Regenerates src/BlazorA2UI.Core/Text/Uax31Tables.cs from Python's Unicode database.

str.isidentifier() checks XID_Start / XID_Continue directly, so the tables match the
Unicode version of the Python that runs this script (printed in the generated header).
Run: python3 tools/generate-xid-tables.py
"""
import pathlib
import unicodedata


def ranges(pred):
    result, start = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            result.append((start, cp - 1))
            start = None
    if start is not None:
        result.append((start, 0x10FFFF))
    return result


def is_start(cp):
    return not 0xD800 <= cp <= 0xDFFF and chr(cp) != "_" and chr(cp).isidentifier()


def is_continue(cp):
    return not 0xD800 <= cp <= 0xDFFF and ("a" + chr(cp)).isidentifier()


def emit(name, rs):
    flat = [x for pair in rs for x in pair]
    lines = ["        " + ", ".join("0x%X" % v for v in flat[i:i + 8]) + "," for i in range(0, len(flat), 8)]
    return (f"    /// <summary>\n    /// Inclusive start/end pairs, sorted.\n    /// </summary>\n"
            f"    internal static readonly int[] s_{name[0].lower() + name[1:]} =\n    [\n" + "\n".join(lines) + "\n    ];\n")


out = f"""// <auto-generated>
// XID_Start and XID_Continue ranges from the Unicode Character Database {unicodedata.unidata_version}
// (DerivedCoreProperties.txt). Generated by tools/generate-xid-tables.py; do not edit by hand.
// </auto-generated>

namespace BlazorA2UI.Text;

internal static class Uax31Tables
{{
{emit("XidStart", ranges(is_start))}
{emit("XidContinue", ranges(is_continue))}}}
"""
target = pathlib.Path(__file__).resolve().parent.parent / "src/BlazorA2UI.Core/Text/Uax31Tables.cs"
target.write_text("\ufeff" + out, encoding="utf-8")
